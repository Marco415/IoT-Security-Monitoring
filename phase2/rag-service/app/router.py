# NEO4J NODE CONVERSION
# ============================================================

def convert_node(node):
    """
    Convert a Neo4j Node or dictionary into the normalized
    EvidenceNode format expected by the RAG API.

    Output:

        {
            "id": "...",
            "label": "...",
            "properties": {...}
        }
    """

    if node is None:
        return None

    # ========================================================
    # DICTIONARY
    # ========================================================

    if isinstance(node, dict):

        labels = node.get(
            "labels",
            []
        )

        properties = node.get(
            "properties",
            {}
        )

        # If this is a plain property dictionary,
        # treat all fields as properties.
        if not properties:

            properties = {
                key: value
                for key, value in node.items()
                if key not in {
                    "id",
                    "label",
                    "labels",
                }
            }

        # Normalize labels.
        if isinstance(
            labels,
            str
        ):

            label = labels

        elif labels:

            label = str(
                labels[0]
            )

        else:

            label = (
                node.get("label")
                or "Node"
            )

        # Stable business identifier.
        node_id = (
            node.get("id")
            or properties.get("alertId")
            or properties.get("eventId")
            or properties.get("userId")
            or properties.get("deviceId")
            or properties.get("serviceId")
            or properties.get("vulnerabilityId")
            or properties.get("procedureId")
            or properties.get("controlId")
            or properties.get("name")
        )

        return {
            "id": (
                str(node_id)
                if node_id is not None
                else None
            ),
            "label": label,
            "properties": properties,
        }

    # ========================================================
    # NATIVE NEO4J NODE
    # ========================================================

    labels = list(
        node.labels
    )

    properties = dict(
        node
    )

    node_id = (
        properties.get("alertId")
        or properties.get("eventId")
        or properties.get("userId")
        or properties.get("deviceId")
        or properties.get("serviceId")
        or properties.get("vulnerabilityId")
        or properties.get("procedureId")
        or properties.get("controlId")
        or properties.get("name")
        or str(node.id)
    )

    label = (
        str(labels[0])
        if labels
        else "Node"
    )

    return {
        "id": str(node_id),
        "label": label,
        "properties": properties,
    }


# ============================================================
# RELATIONSHIP CONVERSION
# ============================================================

def convert_relationship(
    relationship
):

    if not relationship:
        return None

    # --------------------------------------------------------
    # Dictionary representation
    # --------------------------------------------------------

    if isinstance(
        relationship,
        dict
    ):

        source = relationship.get(
            "source"
        )

        target = relationship.get(
            "target"
        )

        relation = relationship.get(
            "relationship"
        )

        if not source or not target or not relation:
            return None

        return EvidenceRelationship(
            source=str(source),
            relationship=str(relation),
            target=str(target)
        )

    # --------------------------------------------------------
    # Native Neo4j relationship
    # --------------------------------------------------------

    try:

        relation_type = (
            relationship.type
        )

        source = (
            relationship.start_node
        )

        target = (
            relationship.end_node
        )

        source_node = convert_node(
            source
        )

        target_node = convert_node(
            target
        )

        if not source_node or not target_node:
            return None

        return EvidenceRelationship(
            source=str(
                source_node["id"]
            ),
            relationship=str(
                relation_type
            ),
            target=str(
                target_node["id"]
            )
        )

    except Exception:
        return None


