# ============================================================
# MAIN RAG ENDPOINT
# ============================================================

@router.post(
    "/ask",
    response_model=RAGResponse
)
def ask_rag(
    request: RAGRequest
):

    # ========================================================
    # VALIDATE QUESTION
    # ========================================================

    question = request.question.strip()

    if not question:

        raise HTTPException(
            status_code=400,
            detail="Question cannot be empty."
        )

    # ========================================================
    # DETECT INTENT
    # ========================================================

    intent = detect_intent(
        question
    )

    # ========================================================
    # RETRIEVE GRAPH EVIDENCE
    # ========================================================

    try:

        records = retrieve_for_intent(
            intent,
            question
        )

    except HTTPException:
        raise

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=(
                "Neo4j graph retrieval failed: "
                f"{exc}"
            )
        )

    if records is None:
        records = []

    # ========================================================
    # NORMALIZE EVIDENCE
    # ========================================================

    nodes, relationships = (
        build_generic_evidence(
            records
        )
    )

    # ========================================================
    # NO EVIDENCE
    # ========================================================

    if not nodes:

        answer = (
            "The knowledge graph did not return "
            "evidence relevant to this question."
        )

        return RAGResponse(
            question=question,
            intent=intent,
            answer=answer,
            retrieval_method=(
                "Cypher graph traversal"
            ),
            evidence_nodes=[],
            evidence_relationships=[],
            evidence_count=0,
            grounding=(
                "No relevant Neo4j evidence "
                "was retrieved."
            ),
            evidence_summary=(
                "No evidence was retrieved."
            )
        )

    # ========================================================
    # CONVERT EVIDENCE TO TEXT
    # ========================================================

    evidence_text = evidence_to_text(
        nodes,
        relationships
    )

    # ========================================================
    # BUILD QWEN3 PROMPT
    # ========================================================

    prompt = PromptBuilder.build(
        question=question,
        intent=intent,
        evidence=evidence_text
    )

    # ========================================================
    # QWEN3 GENERATION
    # ========================================================

    try:

        answer = ollama.generate(
            prompt
        )

    except Exception as exc:

        raise HTTPException(
            status_code=502,
            detail=(
                "Qwen3/Ollama generation failed: "
                f"{exc}"
            )
        )

    # ========================================================
    # RESPONSE
    # ========================================================

    evidence_count = (
        len(nodes)
        + len(relationships)
    )

    return RAGResponse(
        question=question,
        intent=intent,
        answer=answer,
        retrieval_method=(
            "Cypher graph traversal + Qwen3"
        ),
        evidence_nodes=nodes,
        evidence_relationships=relationships,
        evidence_count=evidence_count,
        grounding=(
            "The response was generated from "
            "retrieved Neo4j graph evidence."
        ),
        evidence_summary=(
            build_evidence_summary(
                nodes,
                relationships
            )
        )
    )