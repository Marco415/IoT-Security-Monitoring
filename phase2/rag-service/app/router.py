# ============================================================
# RETRIEVAL DISPATCHER
# ============================================================

def retrieve_for_intent(
    intent: str,
    question: str
):
    """
    Resolve the detected intent into the appropriate
    GraphRetriever operation.
    """

    alert_id = extract_alert_id(
        question
    )

    event_id = extract_event_id(
        question
    )

    user_id = extract_user_id(
        question
    )

    service_name = extract_service_name(
        question
    )

    device_id = extract_device_id(
        question
    )

    threat_name = extract_threat_name(
        question
    )

    control_name = extract_control_name(
        question
    )

    # ========================================================
    # ALERT INVESTIGATION
    # ========================================================

    if intent == "alert_investigation":

        if not alert_id:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify an alert ID."
                )
            )

        return retriever.retrieve_alert_investigation(
            alert_id
        )

    # ========================================================
    # ALERT THREAT
    # ========================================================

    if intent == "alert_threat":

        if not alert_id:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify an alert ID."
                )
            )

        return retriever.retrieve_alert_investigation(
            alert_id
        )

    # ========================================================
    # ALERT RESPONSE
    # ========================================================

    if intent == "alert_response":

        if not alert_id:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify an alert ID."
                )
            )

        # The alert investigation already traverses:
        #
        # Alert -> Threat -> Control
        #
        # and therefore provides useful response context.
        #
        # If a dedicated alert-response retriever is added
        # later, this branch can be switched to it.

        return retriever.retrieve_alert_investigation(
            alert_id
        )

    # ========================================================
    # ALERT SERVICE
    # ========================================================

    if intent == "alert_service":

        if not alert_id:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify an alert ID."
                )
            )

        return retriever.retrieve_alert_investigation(
            alert_id
        )

    # ========================================================
    # THREAT CONTROLS
    # ========================================================

    if intent == "threat_controls":

        if alert_id:

            return retriever.retrieve_threat_controls(
                alert_id
            )

        if threat_name:

            # Requires retrieve_threat_controls_by_name()
            # in GraphRetriever.
            if hasattr(
                retriever,
                "retrieve_threat_controls_by_name"
            ):

                return (
                    retriever
                    .retrieve_threat_controls_by_name(
                        threat_name
                    )
                )

            # Fall back to general threat investigation
            # if the dedicated method does not yet exist.
            return (
                retriever
                .retrieve_threat_investigation(
                    threat_name
                )
            )

        raise HTTPException(
            status_code=400,
            detail=(
                "Could not identify an alert or threat."
            )
        )

    # ========================================================
    # USER EVENTS
    # ========================================================

    if intent == "user_events":

        if not user_id:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify a user."
                )
            )

        return retriever.retrieve_user_events(
            user_id
        )

    # ========================================================
    # USER ALERTS
    # ========================================================

    if intent == "user_alerts":

        if not user_id:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify a user."
                )
            )

        return retriever.retrieve_user_alerts(
            user_id
        )

    # ========================================================
    # EVENT INVESTIGATION
    # ========================================================

    if intent == "event_investigation":

        if not event_id:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify an event ID."
                )
            )

        return retriever.retrieve_event_investigation(
            event_id
        )

    # ========================================================
    # EVENT ALERTS
    # ========================================================

    if intent == "event_alerts":

        if not event_id:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify an event ID."
                )
            )

        return retriever.retrieve_event_investigation(
            event_id
        )

    # ========================================================
    # EVENT USER
    # ========================================================

    if intent == "event_user":

        if not event_id:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify an event ID."
                )
            )

        return retriever.retrieve_event_investigation(
            event_id
        )

    # ========================================================
    # THREAT INVESTIGATION
    # ========================================================

    if intent == "threat_investigation":

        if not threat_name:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify a threat."
                )
            )

        return retriever.retrieve_threat_investigation(
            threat_name
        )

    # ========================================================
    # THREAT ALERTS
    # ========================================================

    if intent == "threat_alerts":

        if not threat_name:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Could not identify a threat."
                )
            )

        return retriever.retrieve_threat_alerts(
            threat_name
        )

    # ========================================================
    # THREAT VULNERABILITIES
    # ========================================================

