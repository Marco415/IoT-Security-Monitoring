# INTENT DETECTION
# ============================================================

def detect_intent(
    question: str
) -> str:
    """
    Determine which graph retrieval operation should be used.

    The classifier intentionally remains deterministic so that
    retrieval behaviour is predictable and easy to demonstrate.

    Supported intents:

        alert_investigation
        alert_threat
        alert_response
        alert_service

        user_events
        user_alerts

        event_investigation
        event_alerts
        event_user

        threat_investigation
        threat_alerts
        threat_controls
        threat_vulnerabilities
        threat_response

        control_investigation
        control_threats

        service_dependencies
        service_investigation

        device_events
        device_alerts

        vulnerability_investigation
        response_investigation

        security_overview
    """

    q = question.lower().strip()

    # ========================================================
    # ALERTS
    # ========================================================

    if "alert-" in q:

        # Controls / mitigation take priority.
        if contains_any(
            q,
            [
                "control",
                "controls",
                "mitigate",
                "mitigates",
                "mitigation",
                "prevent",
                "prevention",
                "protect",
            ]
        ):
            return "threat_controls"

        # Response / remediation.
        if contains_any(
            q,
            [
                "response",
                "respond",
                "remediation",
                "remediate",
                "what should i do",
                "what should be done",
                "how should i respond",
                "how do i respond",
            ]
        ):
            return "alert_response"

        # Threat / attack.
        if contains_any(
            q,
            [
                "threat",
                "attack",
                "technique",
                "mitre",
                "owasp",
            ]
        ):
            return "alert_threat"

        # Service association.
        if contains_any(
            q,
            [
                "service",
                "services",
                "generated by",
                "came from",
            ]
        ):
            return "alert_service"

        # Events / evidence / investigation.
        if contains_any(
            q,
            [
                "event",
                "events",
                "caused",
                "cause",
                "created",
                "triggered",
                "evidence",
                "investigate",
                "investigation",
                "why",
                "happen",
                "happened",
                "generated",
                "details",
                "information",
                "explain",
                "explanation",
            ]
        ):
            return "alert_investigation"

        # Default for a question containing a specific alert.
        return "alert_investigation"

    # ========================================================
    # EVENTS
    # ========================================================

    if "event-" in q:

        if contains_any(
            q,
            [
                "alert",
                "alerts",
                "created",
                "caused",
                "associated",
                "resulted",
            ]
        ):
            return "event_alerts"

        if contains_any(
            q,
            [
                "user",
                "who",
                "account",
                "actor",
            ]
        ):
            return "event_user"

        return "event_investigation"

    # ========================================================
    # USERS
    # ========================================================

    if contains_any(
        q,
        [
            "user",
            "username",
            "account",
            "actor",
        ]
    ):

        if contains_any(
            q,
            [
                "alert",
                "alerts",
            ]
        ):
            return "user_alerts"

        if contains_any(
            q,
            [
                "event",
                "events",
                "activity",
                "activities",
                "actions",
                "login",
                "logins",
            ]
        ):
            return "user_events"

    # ========================================================
    # THREATS
    # ========================================================

    if contains_any(
        q,
        [
            "threat",
            "threats",
            "attack technique",
            "attack techniques",
            "mitre",
            "owasp",
            "brute force",
            "password spraying",
            "broken object level authorization",
            "unrestricted resource consumption",
        ]
    ):

        if contains_any(
            q,
            [
                "control",
                "controls",
                "mitigate",
                "mitigation",
                "prevent",
                "prevention",
                "protect",
            ]
        ):
            return "threat_controls"

        if contains_any(
            q,
            [
                "vulnerability",
                "vulnerabilities",
                "cwe",
                "cve",
            ]
        ):
            return "threat_vulnerabilities"

        if contains_any(
            q,
            [
                "response",
                "respond",
                "remediation",
                "procedure",
                "procedures",
                "incident response",
            ]
        ):
            return "threat_response"

        if contains_any(
            q,
            [
                "alert",
                "alerts",
            ]
        ):
            return "threat_alerts"

        return "threat_investigation"

    # ========================================================
    # CONTROLS
    # ========================================================

    if contains_any(
        q,
        [
            "control",
            "controls",
            "security control",
            "security controls",
        ]
    ):

        if contains_any(
            q,
            [
                "threat",
                "threats",
                "attack",
                "attacks",
            ]
        ):
            return "control_threats"

        return "control_investigation"

    # ========================================================
    # SERVICES
    # ========================================================

    if contains_any(
        q,
        [
            "service",
            "services",
            "microservice",
            "microservices",
        ]
    ):

        if contains_any(
            q,
            [
                "depend",
                "dependency",
                "dependencies",
                "affected",
                "impact",
                "fails",
                "fail",
                "failure",
                "down",
                "relies",
                "rely",
                "relies on",
            ]
        ):
            return "service_dependencies"

        return "service_investigation"

    # ========================================================
    # DEVICES
    # ========================================================

    if contains_any(
        q,
        [
            "device",
            "devices",
            "iot device",
            "iot devices",
        ]
    ):

        if contains_any(
            q,
            [
                "alert",
                "alerts",
            ]
        ):
            return "device_alerts"

        return "device_events"

    # ========================================================
    # VULNERABILITIES
    # ========================================================

    if contains_any(
        q,
        [
            "vulnerability",
            "vulnerabilities",
            "cwe-",
            "cve-",
        ]
    ):
        return "vulnerability_investigation"

    # ========================================================
    # RESPONSE PROCEDURES
    # ========================================================

    if contains_any(
        q,
        [
            "response procedure",
            "response procedures",
            "incident response",
            "remediation procedure",
            "remediation procedures",
        ]
    ):
        return "response_investigation"

    # ========================================================
    # GENERAL SECURITY QUESTIONS
    # ========================================================

    return "security_overview"


# ============================================================
# ID / ENTITY EXTRACTION
# ============================================================

def extract_alert_id(
    question: str
):

    match = re.search(
        r"\balert-\d+\b",
        question.lower()
    )

    if match:
        return match.group(0)

    return None


def extract_event_id(
    question: str
):

    match = re.search(
        r"\bevent-\d+\b",
        question.lower()
    )

    if match:
        return match.group(0)

    return None


def extract_user_id(
    question: str
):

    q = question.lower()

    # Explicit user identifiers.
    match = re.search(
        r"\buser[-_]?[a-zA-Z0-9]+\b",
        q
    )

    if match:
        return match.group(0)

    # Known usernames.
    for user in KNOWN_USERS:

        if re.search(
            rf"\b{re.escape(user)}\b",
            q
        ):
            return user

    return None


def extract_service_name(
    question: str
):

    q = question.lower()

    for service in KNOWN_SERVICES:

        if service in q:
            return service

    return None


def extract_device_id(
    question: str
):
    """
    Extract an IoT device identifier.

    Supported examples:

        IOT-001
        IOT-002
        iot-001
        DEVICE-001
        device-001
        device_001
    """

    q = question.lower()

    patterns = [
        r"\biot-\d+\b",
        r"\bdevice-\d+\b",
        r"\bdevice_\d+\b",
    ]

    for pattern in patterns:

        match = re.search(
            pattern,
            q
        )

        if match:

            return match.group(0).upper()

    return None


def extract_threat_name(
    question: str
):

    q = question.lower()

    for threat in KNOWN_THREATS:

        if threat in q:
            return threat

    return None


def extract_control_name(
    question: str
):

    q = question.lower()

    for control in KNOWN_CONTROLS:

        if control in q:
            return control

    return None


