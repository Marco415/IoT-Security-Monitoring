# GENERIC EVIDENCE BUILDER
# ============================================================

def build_generic_evidence(
    records
):
    """
    Normalize Neo4j retrieval results into the API's
    EvidenceNode and EvidenceRelationship structures.

    This replaces the need for a separate evidence builder
    for every retrieval intent.
    """

    nodes = []
    relationships = []

    node_ids = set()
    relationship_ids = set()

    # ========================================================
    # NODE KEYS
    # ========================================================

    node_keys = {
        "alert",
        "alerts",

        "event",
        "events",

        "user",
        "users",

        "threat",
        "threats",

        "control",
        "controls",

        "service",
        "services",

        "failed",

        "affected_services",

        "device",
        "devices",

        "vulnerability",
        "vulnerabilities",

        "procedure",
        "procedures",

        "response_procedure",
        "response_procedures",

        "dependent",
        "dependents",

        "dependency",
        "dependencies",
    }

    # ========================================================
    # RELATIONSHIP KEYS
    # ========================================================

    relationship_keys = {
        "event_alert_relationships",
        "user_event_relationships",
        "alert_threat_relationships",
        "control_threat_relationships",
        "dependency_relationships",
        "vulnerability_threat_relationships",
        "procedure_relationships",
        "threat_control_relationships",
        "threat_alert_relationships",
        "event_user_relationships",
        "device_event_relationships",
        "device_alert_relationships",
    }

    # ========================================================
    # RECORDS
    # ========================================================

    for record in records:

        if not isinstance(
            record,
            dict
        ):
            continue

        # ----------------------------------------------------
        # NODES
        # ----------------------------------------------------

        for key in node_keys:

            value = record.get(
                key
            )

            if value is None:
                continue

            if not isinstance(
                value,
                list
            ):
                value = [value]

            for item in value:

                if not item:
                    continue

                node = convert_node(
                    item
                )

                if not node:
                    continue

                node_id = node.get(
                    "id"
                )

                if (
                    node_id is not None
                    and node_id not in node_ids
                ):

                    nodes.append(
                        node
                    )

                    node_ids.add(
                        node_id
                    )

        # ----------------------------------------------------
        # RELATIONSHIPS
        # ----------------------------------------------------

        for key in relationship_keys:

            value = record.get(
                key
            )

            if not value:
                continue

            # Flatten nested relationship lists.
            flattened = []

            if isinstance(
                value,
                list
            ):

                for item in value:

                    if isinstance(
                        item,
                        list
                    ):

                        flattened.extend(
                            item
                        )

                    else:

                        flattened.append(
                            item
                        )

            else:

                flattened.append(
                    value
                )

            for item in flattened:

                relationship = (
                    convert_relationship(
                        item
                    )
                )

                if not relationship:
                    continue

                relationship_key = (
                    relationship.source,
                    relationship.relationship,
                    relationship.target
                )

                if (
                    relationship_key
                    not in relationship_ids
                ):

                    relationships.append(
                        relationship
                    )

                    relationship_ids.add(
                        relationship_key
                    )

    return nodes, relationships


# ============================================================
# EVIDENCE TEXT FOR QWEN3
# ============================================================

def evidence_to_text(
    nodes,
    relationships
):
    """
    Convert normalized graph evidence into a compact,
    structured text representation for Qwen3.
    """

    lines = []

    # ========================================================
    # NODES
    # ========================================================

    if nodes:

        lines.append(
            "NODES:"
        )

        for node in nodes:

            if not isinstance(
                node,
                dict
            ):
                continue

            node_id = node.get(
                "id"
            )

            label = node.get(
                "label",
                "Node"
            )

            properties = node.get(
                "properties",
                {}
            )

            lines.append(
                f"- {label} "
                f"(id={node_id}): "
                f"{properties}"
            )

    # ========================================================
    # RELATIONSHIPS
    # ========================================================

    if relationships:

        lines.append("")

        lines.append(
            "RELATIONSHIPS:"
        )

        for relationship in relationships:

            if isinstance(
                relationship,
                dict
            ):

                source = relationship.get(
                    "source"
                )

                relationship_type = (
                    relationship.get(
                        "relationship"
                    )
                )

                target = relationship.get(
                    "target"
                )

            else:

                source = (
                    relationship.source
                )

                relationship_type = (
                    relationship.relationship
                )

                target = (
                    relationship.target
                )

            lines.append(
                f"- {source} "
                f"-[{relationship_type}]-> "
                f"{target}"
            )

    if not lines:

        return (
            "No graph evidence was retrieved."
        )

    return "\n".join(lines)


